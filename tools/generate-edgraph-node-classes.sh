#!/usr/bin/env bash
# Generates UAssetAPI/ExportTypes/EdGraphNodeClasses.g.cs from an Unreal Engine source tree.
# Usage: tools/generate-edgraph-node-classes.sh <Engine directory> [extra source roots...]
#
# Lists every UCLASS that descends from UEdGraphNode, with its module (the nearest *.Build.cs) and the data its
# Serialize writes after the pins. Every UEdGraphNode::Serialize ends with the owning pin array. Of the engine's node
# classes, only these subclass trees append persistent data of their own (checked against 5.8.3's Serialize bodies):
#   UK2Node_EditablePinBase  the user-defined pin array (FUserPinInfo)
#   UK2Node_DynamicCast      PureState (one byte)
#   UDataflowEdNode          DataflowNodeGuid
# A new engine release can add others: recheck the Serialize overrides of the listed classes when regenerating.
set -euo pipefail
engine=$1; shift
out=$(dirname "$0")/../UAssetAPI/ExportTypes/EdGraphNodeClasses.g.cs
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT

rg -P --no-config --no-heading --with-filename -U -o --glob '*.h' \
  -e 'class\s+(?:\w+(?:\([^)]*\))?\s+)*?U([A-Z]\w*)\s*(?:final\s*)?:\s*public\s+(?:\w+::)*U(\w+)' -r 'U$1 U$2' \
  "$engine/Source" "$engine/Plugins" "$@" |
  awk -F: '{split($NF,a," "); if (a[1] != a[2]) print a[1]"\t"a[2]"\t"$1}' | sort -u > "$tmp/inherit.tsv"

awk -F'\t' '{p[$1]=$2; f[$1]=$3}
  END {
    desc["UEdGraphNode"]=1; changed=1
    while (changed) { changed=0; for (c in p) if (!(c in desc) && (p[c] in desc)) { desc[c]=1; changed=1 } }
    for (c in desc) {
      if (c == "UEdGraphNode") continue
      x=c; t="None"; depth=0
      while ((x in p) && depth++ < 64) {
        if (x=="UK2Node_EditablePinBase") { t="UserDefinedPins"; break }
        if (x=="UK2Node_DynamicCast") { t="DynamicCastPureState"; break }
        if (x=="UDataflowEdNode") { t="DataflowNodeGuid"; break }
        x=p[x]
      }
      print substr(c,2)"\t"t"\t"f[c]
    }
  }' "$tmp/inherit.tsv" |
while IFS=$'\t' read -r cls tail header; do
  dir=$(dirname "$header"); module=""
  while [ "$dir" != "/" ]; do
    build=$(ls "$dir"/*.[Bb]uild.cs 2>/dev/null | head -1 || true)
    if [ -n "$build" ]; then module=$(basename "$build"); module=${module%.*.cs}; break; fi
    dir=$(dirname "$dir")
  done
  [ -n "$module" ] || { echo "no module for $cls ($header)" >&2; exit 1; }
  printf '%s\t%s\t%s\n' "$module" "$cls" "$tail"
done | sort > "$tmp/table.tsv"

{
  echo '// Generated by tools/generate-edgraph-node-classes.sh. Do not edit.'
  echo 'using System.Collections.Generic;'
  echo
  echo 'namespace UAssetAPI.ExportTypes;'
  echo
  echo 'internal static class EdGraphNodeClasses'
  echo '{'
  echo '    /// <summary>Every native UEdGraphNode class, keyed by /Script module and class name, with the data it writes after its pins.</summary>'
  echo '    internal static readonly Dictionary<(string Module, string Class), EdGraphNodeTail> Tails = new()'
  echo '    {'
  awk -F'\t' '{printf "        [(\"/Script/%s\", \"%s\")] = EdGraphNodeTail.%s,\n", $1, $2, $3}' "$tmp/table.tsv"
  echo '    };'
  echo '}'
} > "$out"
echo "wrote $(wc -l < "$tmp/table.tsv") classes to $out"
